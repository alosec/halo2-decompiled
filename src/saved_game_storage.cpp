/* writes the save image into a game variant's saved game directory; the
   other types have none */
// @retail 0x216f80
bool saved_game_file_write_save_image(long type, s_saved_game_file_location *location)
{
	long bounded = type < k_saved_game_file_first_variant_type ? k_saved_game_file_first_variant_type :
		(type > k_saved_game_file_last_variant_type ? k_saved_game_file_last_variant_type : type);
	if (bounded != type)
	{
		return true;
	}
	char path[256];
	path[0] = 0;
	strncpy(path, location->name, sizeof(path));
	path[255] = 0;
	function_122810(path, "SaveImage.xbx");
	s_type_acf665 file;
	memset(&file, 0, sizeof(file));
	file.signature = FILE_REFERENCE_SIGNATURE;
	file.location = NONE;
	if (file.flags & 1)
		function_1373c0(file.path);
	function_137320(file.path, path);
	file.flags |= 1;
	dword error;
	return (function_1367d0(&file) &&
		function_136970(&file, 2, &error) &&
		function_136d00(&file, g_saved_game_image, sizeof(g_saved_game_image)) &&
		function_136bb0(&file));
}

