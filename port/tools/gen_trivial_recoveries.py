#!/usr/bin/env python3
"""Write port/recovered/trivial_functions.cpp: C++ for every retail function
that no source recovers and whose whole body is one of a few trivial x86
idioms (an empty function, or one returning a constant).

Such functions are mostly default virtual methods (empty handlers, "not
supported" answers) that game and library vtables point at; the whole image
reaches them through the retail vtables it binds. On ARM the calling
convention and the argument count do not matter for a body that ignores its
arguments, so each becomes a parameterless function returning `long` (or
nothing).

usage: gen_trivial_recoveries.py [--xbe orig/game/default.xbe]"""
import argparse
import csv
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# (pattern over the whole body, the C++ body, what it is)
IDIOMS = [
    (rb"\xc3", None, "ret"),
    (rb"\xc2(.)\x00", None, "ret n"),
    (rb"\x33\xc0\xc3", "0", "xor eax, eax; ret"),
    (rb"\x33\xc0\xc2.\x00", "0", "xor eax, eax; ret n"),
    (rb"\x32\xc0\xc3", "0", "xor al, al; ret"),
    (rb"\x32\xc0\xc2.\x00", "0", "xor al, al; ret n"),
    (rb"\xb0\x01\xc3", "1", "mov al, 1; ret"),
    (rb"\xb0\x01\xc2.\x00", "1", "mov al, 1; ret n"),
    (rb"\x83\xc8\xff\xc3", "-1", "or eax, -1; ret"),
    (rb"\x83\xc8\xff\xc2.\x00", "-1", "or eax, -1; ret n"),
    (rb"\xb8(....)\xc3", "imm", "mov eax, imm; ret"),
    (rb"\xb8(....)\xc2.\x00", "imm", "mov eax, imm; ret n"),
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--xbe", type=Path, default=ROOT / "orig/game/default.xbe")
    args = parser.parse_args()
    xbe = args.xbe.read_bytes()
    base = struct.unpack_from("<I", xbe, 0x104)[0]
    headers = struct.unpack_from("<I", xbe, 0x120)[0] - base
    _, va, _, raw, size = struct.unpack_from("<IIIII", xbe, headers)
    text = xbe[raw:raw + size]

    tagged = set()
    for source in list((ROOT / "src").rglob("*.cpp")) + list((ROOT / "port/recovered").glob("*.cpp")):
        if source.name == "trivial_functions.cpp":
            continue
        tagged.update(int(m, 16) for m in re.findall(r"@retail 0x([0-9a-f]+)", source.read_text(errors="replace")))

    found = []
    with (ROOT / "config/functions.csv").open(newline="") as handle:
        for row in csv.DictReader(handle):
            address = int(row["va"], 16)
            length = int(row["size"])
            if row["source"] or address in tagged or not va <= address < va + size or length > 8:
                continue
            body = text[address - va:address - va + length]
            for pattern, value, idiom in IDIOMS:
                m = re.fullmatch(pattern, body, re.S)
                if not m:
                    continue
                if value == "imm":
                    value = f"0x{struct.unpack('<I', m.group(1))[0]:x}"
                found.append((address, value, idiom, row["owner"]))
                break

    lines = [
        "// @flags /O2",
        "// Generated by port/tools/gen_trivial_recoveries.py: the retail functions no",
        "// source recovers whose whole body is a trivial idiom (mostly default",
        "// virtual methods that game and library vtables point at). Do not edit;",
        "// rerun the script.",
        "",
    ]
    for address, value, idiom, owner in found:
        lines.append(f"/* {idiom} ({owner}) */")
        lines.append(f"// @retail 0x{address:x}")
        if value is None:
            lines.append(f"void function_{address:x}(void) {{}}")
        else:
            lines.append(f"long function_{address:x}(void) {{ return {value}; }}")
        lines.append("")
    out = ROOT / "port/recovered/trivial_functions.cpp"
    out.write_text("\n".join(lines))
    print(f"{out.relative_to(ROOT)}: {len(found)} functions")


if __name__ == "__main__":
    main()
