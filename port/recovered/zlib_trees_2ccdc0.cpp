// determines the best encoding for the current block (dynamic trees,
// static trees or store) and outputs it
// @retail 0x2cdf70
void __cdecl tr_flush_block_2cdf70(deflate_state_2cb640 *s, char *buf, unsigned long stored_len, int eof)
{
	unsigned long opt_lenb, static_lenb; // opt_len and static_len in bytes
	int max_blindex = 0; // index of last bit length code of non zero freq

	// build the Huffman trees unless a stored block is forced
	if (s->level > 0)
	{
		// check if the file is ascii or binary
		if (s->data_type == Z_UNKNOWN_2CCDC0)
		{
			set_data_type_2ce570(s);
		}

		// construct the literal and distance trees
		build_tree_2cd220(s, &s->l_desc);
		build_tree_2cd220(s, &s->d_desc);
		// at this point, opt_len and static_len are the total bit lengths
		// of the compressed block data, excluding the tree representations

		// build the bit length tree for the above two trees, and get the
		// index in bl_order of the last bit length code to send
		max_blindex = build_bl_tree_2cda00(s);

		// determine the best encoding: compute first the block length in
		// bytes
		opt_lenb = (s->opt_len + 3 + 7) >> 3;
		static_lenb = (s->static_len + 3 + 7) >> 3;

		if (static_lenb <= opt_lenb)
		{
			opt_lenb = static_lenb;
		}
	}
	else
	{
		opt_lenb = static_lenb = stored_len + 5; // force a stored block
	}

	if (stored_len + 4 <= opt_lenb && buf != (char *)0)
	{
		// 4: two words for the lengths. The test buf != NULL is only
		// necessary if LIT_BUFSIZE > WSIZE; otherwise we can't have
		// processed more than WSIZE input bytes since the last block flush.
		tr_stored_block_2cdce0(s, buf, stored_len, eof);
	}
	else if (static_lenb == opt_lenb)
	{
		send_bits_2ccdc0(s, (STATIC_TREES_2CCDC0 << 1) + eof, 3);
		compress_block_2ce140(s, g_static_ltree_2ccdc0, g_static_dtree_2ccdc0);
	}
	else
	{
		send_bits_2ccdc0(s, (DYN_TREES_2CCDC0 << 1) + eof, 3);
		send_all_trees_2cda70(s, s->l_desc.max_code + 1, s->d_desc.max_code + 1, max_blindex + 1);
		compress_block_2ce140(s, s->dyn_ltree, s->dyn_dtree);
	}
	init_block_2cce20(s);

	if (eof)
	{
		bi_windup_2ce680(s);
	}
}

// sends the block data compressed using the given Huffman trees
// @retail 0x2ce140
void __cdecl compress_block_2ce140(deflate_state_2cb640 *s, ct_data_2cb640 const *ltree,
	ct_data_2cb640 const *dtree)
{
	unsigned int dist; // distance of matched string
	int lc;            // match length or unmatched char (if dist == 0)
	unsigned int lx = 0; // running index in l_buf
	unsigned int code; // the code to send
	int extra;         // number of extra bits to send

	if (s->last_lit != 0)
	{
		do
		{
			dist = s->d_buf[lx];
			lc = s->l_buf[lx++];
			if (dist == 0)
			{
				send_code_2ccdc0(s, lc, ltree); // send a literal byte
			}
			else
			{
				// here, lc is the match length - MIN_MATCH
				code = g_length_code_2ccdc0[lc];
				send_code_2ccdc0(s, code + LITERALS_2CB8C0 + 1, ltree); // send the length code
				extra = g_extra_lbits_2ccdc0[code];
				if (extra != 0)
				{
					lc -= g_base_length_2ccdc0[code];
					send_bits_2ccdc0(s, lc, extra); // send the extra length bits
				}
				dist--; // dist is now the match distance - 1
				code = d_code_2ccdc0(dist);

				send_code_2ccdc0(s, code, dtree); // send the distance code
				extra = g_extra_dbits_2ccdc0[code];
				if (extra != 0)
				{
					dist -= (unsigned int)g_base_dist_2ccdc0[code];
					send_bits_2ccdc0(s, (int)dist, extra); // send the extra distance bits
				}
			} // literal or match pair?
		} while (lx < s->last_lit);
	}

	send_code_2ccdc0(s, END_BLOCK_2CCDC0, ltree);
	s->last_eob_len = ltree[END_BLOCK_2CCDC0].dad_or_len;
}

// sets the data type to ASCII or BINARY, using a crude approximation: binary
// if more than 20% of the bytes are <= 6 or >= 128, ascii otherwise
// @retail 0x2ce570
void __cdecl set_data_type_2ce570(deflate_state_2cb640 *s)
{
	int n = 0;
	unsigned int ascii_freq = 0;
	unsigned int bin_freq = 0;
	while (n < 7)
	{
		bin_freq += s->dyn_ltree[n++].freq_or_code;
	}
	while (n < 128)
	{
		ascii_freq += s->dyn_ltree[n++].freq_or_code;
	}
	while (n < LITERALS_2CB8C0)
	{
		bin_freq += s->dyn_ltree[n++].freq_or_code;
	}
	s->data_type = (unsigned char)(bin_freq > (ascii_freq >> 2) ? Z_BINARY_2CCDC0 : Z_ASCII_2CCDC0);
}

// flushes the bit buffer, keeping at most 7 bits in it
// @retail 0x2ce600
void __cdecl bi_flush_2ce600(deflate_state_2cb640 *s)
{
	if (s->bi_valid == 16)
	{
		put_short_2ccdc0(s, s->bi_buf);
		s->bi_buf = 0;
		s->bi_valid = 0;
	}
	else if (s->bi_valid >= 8)
	{
		put_byte_2ccdc0(s, (unsigned char)s->bi_buf);
		s->bi_buf >>= 8;
		s->bi_valid -= 8;
	}
}

// flushes the bit buffer and aligns the output on a byte boundary
// @retail 0x2ce680
void __cdecl bi_windup_2ce680(deflate_state_2cb640 *s)
{
	if (s->bi_valid > 8)
	{
		put_short_2ccdc0(s, s->bi_buf);
	}
	else if (s->bi_valid > 0)
	{
		put_byte_2ccdc0(s, (unsigned char)s->bi_buf);
	}
	s->bi_buf = 0;
	s->bi_valid = 0;
}

// copies a stored block, storing first the length and its one's
// complement if requested
// @retail 0x2ce6f0
void __cdecl copy_block_2ce6f0(deflate_state_2cb640 *s, char *buf, unsigned int len, int header)
{
	bi_windup_2ce680(s);  // align on byte boundary
	s->last_eob_len = 8; // enough lookahead for inflate

	if (header)
	{
		put_short_2ccdc0(s, (unsigned short)len);
		put_short_2ccdc0(s, (unsigned short)~len);
	}
	while (len--)
	{
		put_byte_2ccdc0(s, *buf++);
	}
}
