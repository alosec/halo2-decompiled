// sends one empty static block to give enough lookahead for inflate (10
// bits of the next block's code plus the EOB of this one)
// @retail 0x2cdd80
void __cdecl tr_align_2cdd80(deflate_state_2cb640 *s)
{
	send_bits_2ccdc0(s, STATIC_TREES_2CCDC0 << 1, 3);
	send_code_2ccdc0(s, END_BLOCK_2CCDC0, g_static_ltree_2ccdc0);
	bi_flush_2ce600(s);
	// Of the 10 bits for the empty block, we have already sent
	// (10 - bi_valid) bits. The lookahead for the last real code (before
	// the EOB of the previous block) was thus at least one plus the length
	// of the EOB plus what we have just sent of the empty static block.
	if (1 + s->last_eob_len + 10 - s->bi_valid < 9)
	{
		send_bits_2ccdc0(s, STATIC_TREES_2CCDC0 << 1, 3);
		send_code_2ccdc0(s, END_BLOCK_2CCDC0, g_static_ltree_2ccdc0);
		bi_flush_2ce600(s);
	}
	s->last_eob_len = 7;
}

