// compares two subtrees, using the tree depth as tie breaker when the
// subtrees have equal frequency
#define smaller_2ccdc0(tree, n, m, depth) \
	(tree[n].freq_or_code < tree[m].freq_or_code || \
		(tree[n].freq_or_code == tree[m].freq_or_code && depth[n] <= depth[m]))

// restores the heap property by moving down the tree starting at node k,
// exchanging a node with the smallest of its two sons if necessary
// @retail 0x2cce90
void __cdecl pqdownheap_2cce90(deflate_state_2cb640 *s, ct_data_2cb640 *tree, int k)
{
	int v = s->heap[k];
	int j = k << 1; // left son of k
	while (j <= s->heap_len)
	{
		// set j to the smallest of the two sons
		if (j < s->heap_len && smaller_2ccdc0(tree, s->heap[j + 1], s->heap[j], s->depth))
		{
			j++;
		}
		// exit if v is smaller than both sons
		if (smaller_2ccdc0(tree, v, s->heap[j], s->depth))
		{
			break;
		}
		// exchange v with the smallest son
		s->heap[k] = s->heap[j];
		k = j;
		// and continue down the tree, setting j to the left son of k
		j <<= 1;
	}
	s->heap[k] = v;
}

// removes the smallest element from the heap and recreates the heap with
// one less element
#define pqremove_2ccdc0(s, tree, top) \
	{ \
		top = s->heap[SMALLEST_2CCDC0]; \
		s->heap[SMALLEST_2CCDC0] = s->heap[s->heap_len--]; \
		pqdownheap_2cce90(s, tree, SMALLEST_2CCDC0); \
	}

// computes the optimal bit lengths for a tree and updates the total bit
// length for the current block (the lengths are limited to max_length)
// @retail 0x2ccf60
void __cdecl gen_bitlen_2ccf60(deflate_state_2cb640 *s, tree_desc_2cb640 *desc)
{
	ct_data_2cb640 *tree = desc->dyn_tree;
	int max_code = desc->max_code;
	ct_data_2cb640 const *stree = STAT_DESC_2CCDC0(desc)->static_tree;
	int const *extra = STAT_DESC_2CCDC0(desc)->extra_bits;
	int base = STAT_DESC_2CCDC0(desc)->extra_base;
	int max_length = STAT_DESC_2CCDC0(desc)->max_length;
	int h;            // heap index
	int n, m;         // iterate over the tree elements
	int bits;         // bit length
	int xbits;        // extra bits
	unsigned short f; // frequency
	int overflow = 0; // number of elements with bit length too large

	for (bits = 0; bits <= MAX_BITS_2CB8C0; bits++)
	{
		s->bl_count[bits] = 0;
	}

	// in a first pass, compute the optimal bit lengths (which may overflow
	// in the case of the bit length tree)
	tree[s->heap[s->heap_max]].dad_or_len = 0; // root of the heap

	for (h = s->heap_max + 1; h < HEAP_SIZE_2CB8C0; h++)
	{
		n = s->heap[h];
		bits = tree[tree[n].dad_or_len].dad_or_len + 1;
		if (bits > max_length)
		{
			bits = max_length, overflow++;
		}
		tree[n].dad_or_len = (unsigned short)bits;
		// we overwrite tree[n].Dad which is no longer needed

		if (n > max_code)
		{
			continue; // not a leaf node
		}

		s->bl_count[bits]++;
		xbits = 0;
		if (n >= base)
		{
			xbits = extra[n - base];
		}
		f = tree[n].freq_or_code;
		s->opt_len += (unsigned long)f * (bits + xbits);
		if (stree)
		{
			s->static_len += (unsigned long)f * (stree[n].dad_or_len + xbits);
		}
	}
	if (overflow == 0)
	{
		return;
	}

	// find the first bit length which could increase
	do
	{
		bits = max_length - 1;
		while (s->bl_count[bits] == 0)
		{
			bits--;
		}
		s->bl_count[bits]--;        // move one leaf down the tree
		s->bl_count[bits + 1] += 2; // move one overflow item as its brother
		s->bl_count[max_length]--;
		// the brother of the overflow item also moves one step up, but this
		// does not affect bl_count[max_length]
		overflow -= 2;
	} while (overflow > 0);

	// now recompute all bit lengths, scanning in increasing frequency
	for (bits = max_length; bits != 0; bits--)
	{
		n = s->bl_count[bits];
		while (n != 0)
		{
			m = s->heap[--h];
			if (m > max_code)
			{
				continue;
			}
			if (tree[m].dad_or_len != (unsigned int)bits)
			{
				s->opt_len += ((long)bits - (long)tree[m].dad_or_len) * (long)tree[m].freq_or_code;
				tree[m].dad_or_len = (unsigned short)bits;
			}
			n--;
		}
	}
}

// reverses the first len bits of a code
static __forceinline unsigned int bi_reverse_2ccdc0(unsigned int code, int len)
{
	unsigned int res = 0;
	do
	{
		res |= code & 1;
		code >>= 1, res <<= 1;
	} while (--len > 0);
	return res >> 1;
}

// generates the codes for a given tree and bit counts (which need not be
// optimal)
// @retail 0x2cd1a0
void __cdecl gen_codes_2cd1a0(ct_data_2cb640 *tree, int max_code, unsigned short *bl_count)
{
	unsigned short next_code[MAX_BITS_2CB8C0 + 1]; // next code value for each bit length
	unsigned short code = 0;                       // running code value
	int bits;                                      // bit index
	int n;                                         // code index

	// the distribution counts are first used to generate the code values
	// without bit reversal
	for (bits = 1; bits <= MAX_BITS_2CB8C0; bits++)
	{
		next_code[bits] = code = (unsigned short)((code + bl_count[bits - 1]) << 1);
	}

	for (n = 0; n <= max_code; n++)
	{
		int len = tree[n].dad_or_len;
		if (len == 0)
		{
			continue;
		}
		// now reverse the bits
		tree[n].freq_or_code = (unsigned short)bi_reverse_2ccdc0(next_code[len]++, len);
	}
}

// constructs one Huffman tree and assigns the code bit strings and
// lengths, updating the total bit length for the current block
// @retail 0x2cd220
void __cdecl build_tree_2cd220(deflate_state_2cb640 *s, tree_desc_2cb640 *desc)
{
	ct_data_2cb640 *tree = desc->dyn_tree;
	ct_data_2cb640 const *stree = STAT_DESC_2CCDC0(desc)->static_tree;
	int elems = STAT_DESC_2CCDC0(desc)->elems;
	int n, m;          // iterate over heap elements
	int max_code = -1; // largest code with non zero frequency
	int node;          // new node being created

	// construct the initial heap, with least frequent element in
	// heap[SMALLEST]; heap[0] is not used
	s->heap_len = 0, s->heap_max = HEAP_SIZE_2CB8C0;

	for (n = 0; n < elems; n++)
	{
		if (tree[n].freq_or_code != 0)
		{
			s->heap[++(s->heap_len)] = max_code = n;
			s->depth[n] = 0;
		}
		else
		{
			tree[n].dad_or_len = 0;
		}
	}

	// the pkzip format requires that at least one distance code exists,
	// and that at least one bit should be sent even if there is only one
	// possible code: force at least two codes of non zero frequency
	while (s->heap_len < 2)
	{
		node = s->heap[++(s->heap_len)] = (max_code < 2 ? ++max_code : 0);
		tree[node].freq_or_code = 1;
		s->depth[node] = 0;
		s->opt_len--;
		if (stree)
		{
			s->static_len -= stree[node].dad_or_len;
		}
		// node is 0 or 1 so it does not have extra bits
	}
	desc->max_code = max_code;

	// the elements heap[heap_len/2+1 .. heap_len] are leaves of the tree;
	// establish sub-heaps of increasing lengths
	for (n = s->heap_len / 2; n >= 1; n--)
	{
		pqdownheap_2cce90(s, tree, n);
	}

	// construct the Huffman tree by repeatedly combining the least two
	// frequent nodes
	node = elems; // next internal node of the tree
	do
	{
		pqremove_2ccdc0(s, tree, n); // n = node of least frequency
		m = s->heap[SMALLEST_2CCDC0]; // m = node of next least frequency

		s->heap[--(s->heap_max)] = n; // keep the nodes sorted by frequency
		s->heap[--(s->heap_max)] = m;

		// create a new node father of n and m
		tree[node].freq_or_code = (unsigned short)(tree[n].freq_or_code + tree[m].freq_or_code);
		s->depth[node] = (unsigned char)(MAX_2CCDC0(s->depth[n], s->depth[m]) + 1);
		tree[n].dad_or_len = tree[m].dad_or_len = (unsigned short)node;

		// and insert the new node in the heap
		s->heap[SMALLEST_2CCDC0] = node++;
		pqdownheap_2cce90(s, tree, SMALLEST_2CCDC0);
	} while (s->heap_len >= 2);

	s->heap[--(s->heap_max)] = s->heap[SMALLEST_2CCDC0];

	// at this point the fields freq and dad are set; generate the bit
	// lengths, then the codes
	gen_bitlen_2ccf60(s, desc);
	gen_codes_2cd1a0(tree, max_code, s->bl_count);
}

// scans a literal or distance tree to determine the frequencies of the
// codes in the bit length tree
// @retail 0x2cd410
void __cdecl scan_tree_2cd410(deflate_state_2cb640 *s, ct_data_2cb640 *tree, int max_code)
{
	int n;                             // iterates over all tree elements
	int prevlen = -1;                  // last emitted length
	int curlen;                        // length of current code
	int nextlen = tree[0].dad_or_len;  // length of next code
	int count = 0;                     // repeat count of the current code
	int max_count = 7;                 // max repeat count
	int min_count = 4;                 // min repeat count

	if (nextlen == 0)
	{
		max_count = 138, min_count = 3;
	}
	tree[max_code + 1].dad_or_len = (unsigned short)0xffff; // guard

	for (n = 0; n <= max_code; n++)
	{
		curlen = nextlen;
		nextlen = tree[n + 1].dad_or_len;
		if (++count < max_count && curlen == nextlen)
		{
			continue;
		}
		else if (count < min_count)
		{
			s->bl_tree[curlen].freq_or_code = (unsigned short)(s->bl_tree[curlen].freq_or_code + count);
		}
		else if (curlen != 0)
		{
			if (curlen != prevlen)
			{
				s->bl_tree[curlen].freq_or_code++;
			}
			s->bl_tree[REP_3_6_2CCDC0].freq_or_code++;
		}
		else if (count <= 10)
		{
			s->bl_tree[REPZ_3_10_2CCDC0].freq_or_code++;
		}
		else
		{
			s->bl_tree[REPZ_11_138_2CCDC0].freq_or_code++;
		}
		count = 0;
		prevlen = curlen;
		if (nextlen == 0)
		{
			max_count = 138, min_count = 3;
		}
		else if (curlen == nextlen)
		{
			max_count = 6, min_count = 3;
		}
		else
		{
			max_count = 7, min_count = 4;
		}
	}
}

// sends a literal or distance tree in compressed form, using the codes in
// bl_tree
// @retail 0x2cd4f0
void __cdecl send_tree_2cd4f0(deflate_state_2cb640 *s, ct_data_2cb640 *tree, int max_code)
{
	int n;                             // iterates over all tree elements
	int prevlen = -1;                  // last emitted length
	int curlen;                        // length of current code
	int nextlen = tree[0].dad_or_len;  // length of next code
	int count = 0;                     // repeat count of the current code
	int max_count = 7;                 // max repeat count
	int min_count = 4;                 // min repeat count

	// tree[max_code+1].Len = -1; guard already set
	if (nextlen == 0)
	{
		max_count = 138, min_count = 3;
	}

	for (n = 0; n <= max_code; n++)
	{
		curlen = nextlen;
		nextlen = tree[n + 1].dad_or_len;
		if (++count < max_count && curlen == nextlen)
		{
			continue;
		}
		else if (count < min_count)
		{
			do
			{
				send_code_2ccdc0(s, curlen, s->bl_tree);
			} while (--count != 0);
		}
		else if (curlen != 0)
		{
			if (curlen != prevlen)
			{
				send_code_2ccdc0(s, curlen, s->bl_tree);
				count--;
			}
			send_code_2ccdc0(s, REP_3_6_2CCDC0, s->bl_tree);
			send_bits_2ccdc0(s, count - 3, 2);
		}
		else if (count <= 10)
		{
			send_code_2ccdc0(s, REPZ_3_10_2CCDC0, s->bl_tree);
			send_bits_2ccdc0(s, count - 3, 3);
		}
		else
		{
			send_code_2ccdc0(s, REPZ_11_138_2CCDC0, s->bl_tree);
			send_bits_2ccdc0(s, count - 11, 7);
		}
		count = 0;
		prevlen = curlen;
		if (nextlen == 0)
		{
			max_count = 138, min_count = 3;
		}
		else if (curlen == nextlen)
		{
			max_count = 6, min_count = 3;
		}
		else
		{
			max_count = 7, min_count = 4;
		}
	}
}

// constructs the Huffman tree for the bit lengths and returns the index in
// bl_order of the last bit length code to send
// @retail 0x2cda00
int __cdecl build_bl_tree_2cda00(deflate_state_2cb640 *s)
{
	int max_blindex; // index of last bit length code of non zero freq

	// determine the bit length frequencies for literal and distance trees
	scan_tree_2cd410(s, s->dyn_ltree, s->l_desc.max_code);
	scan_tree_2cd410(s, s->dyn_dtree, s->d_desc.max_code);

	// build the bit length tree
	build_tree_2cd220(s, &s->bl_desc);
	// opt_len now includes the length of the tree representations, except
	// the lengths of the bit lengths codes and the 5+5+4 bits for the counts

	// determine the number of bit length codes to send (at least 4)
	for (max_blindex = BL_CODES_2CB8C0 - 1; max_blindex >= 3; max_blindex--)
	{
		if (s->bl_tree[g_bl_order_2ccdc0[max_blindex]].dad_or_len != 0)
		{
			break;
		}
	}
	// update opt_len to include the bit length tree and counts
	s->opt_len += 3 * (max_blindex + 1) + 5 + 5 + 4;

	return max_blindex;
}

// sends the header for a block using dynamic Huffman trees: the counts, the
// lengths of the bit length codes, the literal tree and the distance tree
// @retail 0x2cda70
void __cdecl send_all_trees_2cda70(deflate_state_2cb640 *s, int lcodes, int dcodes, int blcodes)
{
	int rank; // index in bl_order

	send_bits_2ccdc0(s, lcodes - 257, 5); // not +255 as stated in appnote.txt
	send_bits_2ccdc0(s, dcodes - 1, 5);
	send_bits_2ccdc0(s, blcodes - 4, 4); // not -3 as stated in appnote.txt
	for (rank = 0; rank < blcodes; rank++)
	{
		send_bits_2ccdc0(s, s->bl_tree[g_bl_order_2ccdc0[rank]].dad_or_len, 3);
	}

	send_tree_2cd4f0(s, s->dyn_ltree, lcodes - 1); // literal tree
	send_tree_2cd4f0(s, s->dyn_dtree, dcodes - 1); // distance tree
}

